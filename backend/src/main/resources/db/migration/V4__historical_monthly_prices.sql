-- Monthly nationwide pepper prices, January 2005 to December 2022.
--
-- Why this exists: the forecasting model had 44 monthly points to learn from,
-- 43 of which were themselves interpolated by an earlier prototype. At that
-- size a gradient-boosted tree loses to assuming the price does not move,
-- which is what ADR-0004 measured and why the naive baseline ships.
--
-- This is the real observed series the project owner collected for the
-- research the prototype was built on (D:\DuBaoGiaTieu\ml\data_raw_monthly.csv,
-- column P_t). It joins the existing history without a gap: December 2022
-- closes at 59,000 and January 2023 opens at 58,700, same units, same basis.
--
-- It matters more than its row count suggests. The 2023-2026 window the model
-- had only ever seen prices between 58k and 137k, with no crash in it. This
-- series contains the 2015 peak at 202,000 and the fall to 41,000 by 2020 —
-- the variance a quantile model needs if its 10-90 band is to mean anything.
--
-- Tagged with its own source so it stays distinguishable from scraped prices
-- and from the interpolated backfill. Dated to the first of each month, the
-- same convention the existing monthly rows use.

